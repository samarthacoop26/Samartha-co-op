export function getCategoryBySlug(slug: string): ProductCategoryDetail | undefined {
  const cleanSlug = slug.toLowerCase().trim();
  return PRODUCT_CATALOG.find(
    (cat) => cat.slug === cleanSlug || cat.aliases.includes(cleanSlug)
  );
}

export function getAllProducts(): ProductItem[] {
  return PRODUCT_CATALOG.flatMap((c) => c.products);
}

export function getProductBySlug(categorySlug: string, productSlug: string): ProductItem | undefined {
  const category = getCategoryBySlug(categorySlug);
  if (!category) return undefined;
  return category.products.find((p) => p.slug === productSlug.toLowerCase().trim());
}

